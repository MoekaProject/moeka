pub(crate) fn format_relative_time(language: UiLanguage, time: std::time::SystemTime) -> String {
    let Ok(delta) = std::time::SystemTime::now().duration_since(time) else {
        return translate(language, TextKey::Current).to_string();
    };

    let seconds = delta.as_secs();
    if seconds < 60 {
        return match language {
            UiLanguage::English => "Just now".to_string(),
            UiLanguage::ChineseSimplified => "刚刚".to_string(),
            UiLanguage::ChineseTraditional => "剛剛".to_string(),
            UiLanguage::Japanese => "たった今".to_string(),
            UiLanguage::Korean => "방금 전".to_string(),
            UiLanguage::French => "À l'instant".to_string(),
            UiLanguage::German => "Gerade eben".to_string(),
            UiLanguage::Spanish => "Ahora mismo".to_string(),
            UiLanguage::Portuguese => "Agora mesmo".to_string(),
            UiLanguage::Russian => "Только что".to_string(),
            UiLanguage::Arabic => "الآن".to_string(),
            UiLanguage::Hindi => "अभी-अभी".to_string(),
        };
    }

    if seconds < 3_600 {
        let value = seconds / 60;
        return match language {
            UiLanguage::English => format!("{value} min ago"),
            UiLanguage::ChineseSimplified => format!("{value} 分钟前"),
            UiLanguage::ChineseTraditional => format!("{value} 分鐘前"),
            UiLanguage::Japanese => format!("{value} 分前"),
            UiLanguage::Korean => format!("{value}분 전"),
            UiLanguage::French => format!("Il y a {value} min"),
            UiLanguage::German => format!("Vor {value} Min."),
            UiLanguage::Spanish => format!("Hace {value} min"),
            UiLanguage::Portuguese => format!("Há {value} min"),
            UiLanguage::Russian => format!("{value} мин назад"),
            UiLanguage::Arabic => format!("قبل {value} دقيقة"),
            UiLanguage::Hindi => format!("{value} मिनट पहले"),
        };
    }

    if seconds < 86_400 {
        let value = seconds / 3_600;
        return match language {
            UiLanguage::English => format!("{value} hr ago"),
            UiLanguage::ChineseSimplified => format!("{value} 小时前"),
            UiLanguage::ChineseTraditional => format!("{value} 小時前"),
            UiLanguage::Japanese => format!("{value} 時間前"),
            UiLanguage::Korean => format!("{value}시간 전"),
            UiLanguage::French => format!("Il y a {value} h"),
            UiLanguage::German => format!("Vor {value} Std."),
            UiLanguage::Spanish => format!("Hace {value} h"),
            UiLanguage::Portuguese => format!("Há {value} h"),
            UiLanguage::Russian => format!("{value} ч назад"),
            UiLanguage::Arabic => format!("قبل {value} ساعة"),
            UiLanguage::Hindi => format!("{value} घंटे पहले"),
        };
    }

    if seconds < 86_400 * 365 {
        let value = seconds / 86_400;
        return match language {
            UiLanguage::English => format!("{value} day{} ago", if value == 1 { "" } else { "s" }),
            UiLanguage::ChineseSimplified => format!("{value} 天前"),
            UiLanguage::ChineseTraditional => format!("{value} 天前"),
            UiLanguage::Japanese => format!("{value} 日前"),
            UiLanguage::Korean => format!("{value}일 전"),
            UiLanguage::French => format!("Il y a {value} j"),
            UiLanguage::German => format!("Vor {value} Tag{}", if value == 1 { "" } else { "en" }),
            UiLanguage::Spanish => format!("Hace {value} día{}", if value == 1 { "" } else { "s" }),
            UiLanguage::Portuguese => {
                format!("Há {value} dia{}", if value == 1 { "" } else { "s" })
            }
            UiLanguage::Russian => format!("{value} дн. назад"),
            UiLanguage::Arabic => format!("قبل {value} يوم"),
            UiLanguage::Hindi => format!("{value} दिन पहले"),
        };
    }

    let value = seconds / (86_400 * 365);
    match language {
        UiLanguage::English => format!("{value} yr{} ago", if value == 1 { "" } else { "s" }),
        UiLanguage::ChineseSimplified => format!("{value} 年前"),
        UiLanguage::ChineseTraditional => format!("{value} 年前"),
        UiLanguage::Japanese => format!("{value} 年前"),
        UiLanguage::Korean => format!("{value}년 전"),
        UiLanguage::French => format!("Il y a {value} an{}", if value == 1 { "" } else { "s" }),
        UiLanguage::German => format!("Vor {value} Jahr{}", if value == 1 { "" } else { "en" }),
        UiLanguage::Spanish => format!("Hace {value} año{}", if value == 1 { "" } else { "s" }),
        UiLanguage::Portuguese => format!("Há {value} ano{}", if value == 1 { "" } else { "s" }),
        UiLanguage::Russian => format!("{value} г. назад"),
        UiLanguage::Arabic => format!("قبل {value} سنة"),
        UiLanguage::Hindi => format!("{value} साल पहले"),
    }
}

fn normalize_locale(value: &str) -> String {
    value
        .split('.')
        .next()
        .unwrap_or(value)
        .replace('_', "-")
        .to_ascii_lowercase()
}

fn is_traditional_chinese(locale: &str) -> bool {
    locale.starts_with("zh-hant")
        || locale.starts_with("zh-tw")
        || locale.starts_with("zh-hk")
        || locale.starts_with("zh-mo")
}

fn read_locale_from_env() -> Option<String> {
    ["LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"]
        .into_iter()
        .find_map(|key| {
            std::env::var(key)
                .ok()
                .filter(|value| !value.trim().is_empty())
        })
}

