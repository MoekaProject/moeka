#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct LanguageOption {
    pub language: UiLanguage,
    pub label: String,
    pub search_text: String,
}

impl UiLanguage {
    pub(crate) fn supported() -> &'static [Self] {
        &[
            Self::English,
            Self::ChineseSimplified,
            Self::ChineseTraditional,
            Self::Japanese,
            Self::Korean,
            Self::French,
            Self::German,
            Self::Spanish,
            Self::Portuguese,
            Self::Russian,
            Self::Arabic,
            Self::Hindi,
        ]
    }

    pub(crate) fn from_code(value: &str) -> Option<Self> {
        let normalized = normalize_locale(value);
        let base = normalized.split('-').next().unwrap_or(normalized.as_str());
        match normalized.as_str() {
            locale if is_traditional_chinese(locale) => Some(Self::ChineseTraditional),
            locale if locale.starts_with("zh") => Some(Self::ChineseSimplified),
            locale if locale.starts_with("ja") => Some(Self::Japanese),
            locale if locale.starts_with("ko") => Some(Self::Korean),
            locale if locale.starts_with("fr") => Some(Self::French),
            locale if locale.starts_with("de") => Some(Self::German),
            locale if locale.starts_with("es") => Some(Self::Spanish),
            locale if locale.starts_with("pt") => Some(Self::Portuguese),
            locale if locale.starts_with("ru") => Some(Self::Russian),
            locale if locale.starts_with("ar") => Some(Self::Arabic),
            locale if locale.starts_with("hi") => Some(Self::Hindi),
            locale if locale.starts_with("en") => Some(Self::English),
            _ => match base {
                "zh" => Some(Self::ChineseSimplified),
                "ja" => Some(Self::Japanese),
                "ko" => Some(Self::Korean),
                "fr" => Some(Self::French),
                "de" => Some(Self::German),
                "es" => Some(Self::Spanish),
                "pt" => Some(Self::Portuguese),
                "ru" => Some(Self::Russian),
                "ar" => Some(Self::Arabic),
                "hi" => Some(Self::Hindi),
                "en" => Some(Self::English),
                _ => None,
            },
        }
    }

    pub(crate) fn code(self) -> &'static str {
        match self {
            Self::English => "en",
            Self::ChineseSimplified => "zh-CN",
            Self::ChineseTraditional => "zh-TW",
            Self::Japanese => "ja",
            Self::Korean => "ko",
            Self::French => "fr",
            Self::German => "de",
            Self::Spanish => "es",
            Self::Portuguese => "pt",
            Self::Russian => "ru",
            Self::Arabic => "ar",
            Self::Hindi => "hi",
        }
    }

    pub(crate) fn native_name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::ChineseSimplified => "简体中文",
            Self::ChineseTraditional => "繁體中文",
            Self::Japanese => "日本語",
            Self::Korean => "한국어",
            Self::French => "Français",
            Self::German => "Deutsch",
            Self::Spanish => "Español",
            Self::Portuguese => "Português",
            Self::Russian => "Русский",
            Self::Arabic => "العربية",
            Self::Hindi => "हिन्दी",
        }
    }

    pub(crate) fn english_name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::ChineseSimplified => "Chinese (Simplified)",
            Self::ChineseTraditional => "Chinese (Traditional)",
            Self::Japanese => "Japanese",
            Self::Korean => "Korean",
            Self::French => "French",
            Self::German => "German",
            Self::Spanish => "Spanish",
            Self::Portuguese => "Portuguese",
            Self::Russian => "Russian",
            Self::Arabic => "Arabic",
            Self::Hindi => "Hindi",
        }
    }

    pub(crate) fn picker_label_for(self, display_language: UiLanguage) -> String {
        if display_language == UiLanguage::English {
            self.english_name().to_string()
        } else {
            self.native_name().to_string()
        }
    }
}

pub(crate) fn detect_system_language() -> UiLanguage {
    sys_locale::get_locale()
        .or_else(read_locale_from_env)
        .as_deref()
        .and_then(UiLanguage::from_code)
        .unwrap_or(UiLanguage::English)
}

pub(crate) fn default_language_code() -> String {
    detect_system_language().code().to_string()
}

pub(crate) fn application_display_name(language: UiLanguage) -> &'static str {
    match language {
        UiLanguage::ChineseSimplified => "小语文稿",
        UiLanguage::ChineseTraditional => "小語文稿",
        _ => "Moeka",
    }
}

pub(crate) fn system_application_display_name() -> &'static str {
    application_display_name(detect_system_language())
}

pub(crate) fn language_picker_options(display_language: UiLanguage) -> Vec<LanguageOption> {
    UiLanguage::supported()
        .iter()
        .copied()
        .map(|language| LanguageOption {
            language,
            label: language.picker_label_for(display_language),
            search_text: format!(
                "{} {} {}",
                language.code().to_lowercase(),
                language.english_name().to_lowercase(),
                language.native_name().to_lowercase(),
            ),
        })
        .collect()
}

pub(crate) fn translate(language: UiLanguage, key: TextKey) -> &'static str {
    match language {
        UiLanguage::English => translate_english(key),
        UiLanguage::ChineseSimplified => translate_zh_cn(key),
        UiLanguage::ChineseTraditional => translate_zh_tw(key),
        UiLanguage::Japanese => translate_japanese(key),
        UiLanguage::Korean => translate_korean(key),
        UiLanguage::French => translate_french(key),
        UiLanguage::German => translate_german(key),
        UiLanguage::Spanish => translate_spanish(key),
        UiLanguage::Portuguese => translate_portuguese(key),
        UiLanguage::Russian => translate_russian(key),
        UiLanguage::Arabic => translate_arabic(key),
        UiLanguage::Hindi => translate_hindi(key),
    }
}

