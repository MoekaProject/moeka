fn command_label_index(language: UiLanguage) -> usize {
    match language {
        UiLanguage::English => 0,
        UiLanguage::ChineseSimplified => 1,
        UiLanguage::ChineseTraditional => 2,
        UiLanguage::Japanese => 3,
        UiLanguage::Korean => 4,
        UiLanguage::French => 5,
        UiLanguage::German => 6,
        UiLanguage::Spanish => 7,
        UiLanguage::Portuguese => 8,
        UiLanguage::Russian => 9,
        UiLanguage::Arabic => 10,
        UiLanguage::Hindi => 11,
    }
}

pub(crate) fn command_label(language: UiLanguage, key: &str) -> &'static str {
    COMMAND_LABELS
        .iter()
        .find(|(label_key, _)| *label_key == key)
        .map(|(_, labels)| labels[command_label_index(language)])
        .unwrap_or("")
}

